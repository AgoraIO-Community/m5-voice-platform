#!/usr/bin/env python3
"""Bake aligned expressions into the existing 84x96 mascot (no image API).

Requires Pillow and numpy. The original sprite, silhouette and alpha are kept;
only measured face regions change. A sampled skin gradient replaces old facial
features, and antialiased paths are composited locally. Firmware swaps whole
images instead of drawing independently positioned overlays over the face.
"""
from pathlib import Path
import numpy as np
from PIL import Image, ImageDraw, ImageFilter

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'assets/sticks3/agora_mascot_sprite.png'
OUT_DIR = ROOT / 'assets/sticks3/mascot_states'
OUT_C = ROOT / 'main/voice_ui_mascot_states.c'
SIZE = (84, 96)
SCALE = 6
INK = (16, 37, 82, 255)
TONGUE = (255, 145, 111, 255)
# Coordinates measured on the firmware sprite, not on the unscaled source.
# Original eyes x17..29 / x54..67, y44..59; mouth x36..48, y57..63.
REGIONS = {'left': (13, 41, 33, 62), 'right': (50, 41, 71, 62),
           'mouth': (32, 53, 53, 70)}


def repair_skin(source, regions):
    """Preserve the source's white-to-blue cheek gradient around each feature."""
    pixels = np.asarray(source)
    gradient = np.zeros_like(pixels)
    gradient[:, :, 3] = 255
    for y in range(SIZE[1]):
        row = pixels[y, 10:74, :3].astype(int)
        skin = ((row[:, 0] > 220) & (row[:, 1] > 235) & (row[:, 2] > 240)
                & (row[:, 2] - row[:, 0] < 28) & (row[:, 1] - row[:, 0] < 18))
        gradient[y, :, :3] = np.median(row[skin], axis=0) if skin.any() else (240, 248, 253)
    mask = Image.new('L', SIZE)
    draw = ImageDraw.Draw(mask)
    for region in regions:
        draw.ellipse(REGIONS[region], fill=255)
    mask = mask.filter(ImageFilter.GaussianBlur(.6))
    cleaned = Image.composite(Image.fromarray(gradient), source, mask)
    cleaned.putalpha(source.getchannel('A'))
    return cleaned, mask


def curve(draw, points, width=1.7, fill=INK):
    """Smooth quadratic curve with round caps, in native sprite coordinates."""
    a, b, c = points
    path = []
    for t in np.linspace(0, 1, 40):
        path.append(tuple(SCALE * ((1-t)**2*a[i] + 2*(1-t)*t*b[i] + t*t*c[i]) for i in (0, 1)))
    draw.line(path, fill=fill, width=round(width*SCALE))
    radius = width*SCALE/2
    for x, y in (path[0], path[-1]):
        draw.ellipse((x-radius, y-radius, x+radius, y+radius), fill=fill)


def expression(name):
    source = Image.open(SOURCE).convert('RGBA')
    regions = {'wink': ['left'], 'listen': ['mouth'],
               'think': ['left', 'right', 'mouth'], 'speak': ['mouth'],
               'sleep': ['left', 'right', 'mouth']}[name]
    cleaned, _ = repair_skin(source, regions)
    # Only the transparent vector layer is downsampled: unedited source pixels
    # are never resampled. Every state keeps the original outline and anchor.
    layer = Image.new('RGBA', (SIZE[0]*SCALE, SIZE[1]*SCALE))
    draw = ImageDraw.Draw(layer)
    if name == 'wink':
        curve(draw, [(16, 52), (21.5, 47.5), (28, 52)])
    elif name == 'listen':
        curve(draw, [(38, 59.5), (42, 63.5), (46, 59.5)], 1.6)
    elif name == 'think':
        curve(draw, [(16, 50.5), (21.5, 55.5), (28, 51)])
        curve(draw, [(55, 51), (60.5, 55.5), (67, 50.5)])
        curve(draw, [(40, 61), (43, 59.5), (46, 61)], 1.5)
    elif name == 'speak':
        draw.ellipse(tuple(v*SCALE for v in (35, 55, 49, 67)), fill=INK)
        draw.ellipse(tuple(v*SCALE for v in (38, 62, 46, 66)), fill=TONGUE)
    elif name == 'sleep':
        curve(draw, [(16, 52), (21.5, 48), (28, 52)])
        curve(draw, [(55, 52), (60.5, 48), (67, 52)])
        curve(draw, [(38, 59.5), (42, 63.5), (46, 59.5)], 1.6)
    layer = layer.resize(SIZE, Image.Resampling.LANCZOS)
    result = Image.alpha_composite(cleaned, layer)
    result.putalpha(source.getchannel('A'))
    original, output = np.asarray(source), np.asarray(result)
    assert np.array_equal(original[:, :, 3], output[:, :, 3]), 'silhouette changed'
    # Outside the measured face, every RGB/alpha byte must match the source.
    unchanged = np.ones(SIZE[::-1], dtype=bool)
    unchanged[38:73, 10:75] = False
    assert np.array_equal(original[unchanged], output[unchanged]), 'body or outline changed'
    return result


def c_bytes(image):
    data = []
    for r, g, b, a in image.getdata():
        value = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
        data.extend((value & 255, value >> 8, a))
    return data


def main():
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    lines = ['/* Generated by ui_tools/generate_mascot_states.py; RGB565 little-endian + A8. */',
             '#include "lvgl.h"', '', '#if LV_COLOR_DEPTH != 16 || LV_COLOR_16_SWAP',
             '#error "voice_ui_mascot_states requires unswapped 16-bit LVGL colors"', '#endif', '']
    names = ('wink', 'listen', 'think', 'speak', 'sleep')
    for name in names:
        image = expression(name)
        image.save(OUT_DIR / f'{name}.png')
        data = c_bytes(image)
        symbol = f'voice_ui_mascot_{name}'
        lines.append(f'static const uint8_t {symbol}_pixels[{len(data)}] = {{')
        for start in range(0, len(data), 24):
            lines.append('    ' + ', '.join(f'0x{v:02x}' for v in data[start:start+24]) + ',')
        lines += ['};', '', f'const lv_img_dsc_t {symbol} = {{',
                  '    .header = {.cf = LV_IMG_CF_TRUE_COLOR_ALPHA, .always_zero = 0, .reserved = 0, .w = 84, .h = 96},',
                  f'    .data_size = sizeof({symbol}_pixels),', f'    .data = {symbol}_pixels', '};', '']
    OUT_C.write_text('\n'.join(lines))
    print(f'Generated {len(names)} aligned state images; original silhouette/body byte-identical.')


if __name__ == '__main__':
    main()
