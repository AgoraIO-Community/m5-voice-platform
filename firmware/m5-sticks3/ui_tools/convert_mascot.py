#!/usr/bin/env python3
"""Convert the approved PNG into a fixed LVGL 8 RGB565+A8 image.

Run from the repository root. Requires Pillow, numpy, opencv-python.
The original AI-generated image is preserved; no image service is called.
"""
from pathlib import Path
import cv2
import numpy as np
from PIL import Image

root = Path(__file__).resolve().parents[1]
source = root / "assets/sticks3/agora_mascot.png"
image = cv2.imread(str(source))
height, width = image.shape[:2]
mask = np.zeros((height, width), np.uint8)
cv2.setRNGSeed(0)
cv2.grabCut(image, mask, (width // 9, height // 14, width * 7 // 9, height * 6 // 7),
            np.zeros((1, 65), np.float64), np.zeros((1, 65), np.float64), 8, cv2.GC_INIT_WITH_RECT)
alpha = np.where((mask == 1) | (mask == 3), 255, 0).astype(np.uint8)
rgba = cv2.cvtColor(image, cv2.COLOR_BGR2RGBA)
rgba[:, :, 3] = alpha
ys, xs = np.where(alpha != 0)
crop = Image.fromarray(rgba).crop((xs.min() - 8, ys.min() - 8, xs.max() + 9, ys.max() + 9))
crop.thumbnail((84, 96), Image.Resampling.LANCZOS)
sprite = Image.new("RGBA", (84, 96))
sprite.paste(crop, ((84 - crop.width) // 2, (96 - crop.height) // 2))
sprite.save(root / "assets/sticks3/agora_mascot_sprite.png")
data = []
for r, g, b, a in sprite.getdata():
    value = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
    data.extend((value & 255, value >> 8, a))
lines = ["/* Generated by ui_tools/convert_mascot.py; RGB565 little-endian + A8. */",
         '#include "lvgl.h"', '',
         '#if LV_COLOR_DEPTH != 16 || LV_COLOR_16_SWAP',
         '#error "voice_ui_mascot requires unswapped 16-bit LVGL colors"', '#endif', '',
         f'static const uint8_t voice_ui_mascot_pixels[{len(data)}] = {{']
for start in range(0, len(data), 24):
    lines.append("    " + ", ".join(f"0x{v:02x}" for v in data[start:start + 24]) + ",")
lines += ["};", "", "const lv_img_dsc_t voice_ui_mascot = {",
          "    .header = {.cf = LV_IMG_CF_TRUE_COLOR_ALPHA, .always_zero = 0, .reserved = 0, .w = 84, .h = 96},",
          "    .data_size = sizeof(voice_ui_mascot_pixels),", "    .data = voice_ui_mascot_pixels", "};", ""]
(root / "main/voice_ui_assets.c").write_text("\n".join(lines))
print(f"84x96 RGB565+A8: {len(data)} bytes (const flash data)")
